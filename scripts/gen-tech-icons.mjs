// Generates src/svg/tech-icons.ts from the `simple-icons` package (CC0).
// Run: node scripts/gen-tech-icons.mjs   (re-run after bumping simple-icons)
// Only a curated set is bundled to keep the Worker small; icons over MAX_PATH bytes are skipped.
import { writeFileSync } from 'node:fs';
import * as si from 'simple-icons';

const MAX_PATH = 8000;

/** slug -> extra aliases users might type. Order = display order in docs. */
const WANTED = {
  // languages
  javascript: ['js'], typescript: ['ts'], python: ['py'], go: ['golang'], rust: ['rs'], openjdk: ['java'], kotlin: ['kt'],
  swift: [], c: [], cplusplus: ['c++', 'cpp'], dotnet: ['.net', 'csharp', 'c#'], php: [], ruby: ['rb'], dart: [], elixir: [],
  scala: [], lua: [], gnubash: ['bash', 'shell', 'sh'], haskell: [], zig: [], julia: [], r: [], perl: [], clojure: [], ocaml: [],
  solidity: [], webassembly: ['wasm'], html5: ['html'], css: ['css3'], sass: ['scss'],
  // frontend
  react: ['reactjs'], vuedotjs: ['vue', 'vuejs'], svelte: [], angular: [], nextdotjs: ['next', 'nextjs'], nuxt: ['nuxtjs'], astro: [],
  remix: [], solid: ['solidjs'], htmx: [], alpinedotjs: ['alpine'], tailwindcss: ['tailwind'], bootstrap: [], mui: ['materialui'],
  redux: [], threedotjs: ['three', 'threejs'], vite: [], webpack: [], babel: [], storybook: [],
  // backend & runtimes
  nodedotjs: ['node', 'nodejs'], deno: [], bun: [], express: ['expressjs'], nestjs: ['nest'], django: [], flask: [], fastapi: [],
  spring: ['springboot'], rubyonrails: ['rails'], laravel: [], graphql: [], prisma: [], trpc: [],
  // mobile & desktop
  flutter: [], android: [], ios: [], expo: [], electron: [], tauri: [],
  // data & ML
  postgresql: ['postgres'], mysql: [], mongodb: ['mongo'], redis: [], sqlite: [], supabase: [], firebase: [], elasticsearch: [],
  apachekafka: ['kafka'], rabbitmq: [], tensorflow: [], pytorch: [], numpy: [], pandas: [], jupyter: [], scikitlearn: ['sklearn'],
  // infra & tools
  docker: [], kubernetes: ['k8s'], googlecloud: ['gcp'], cloudflare: [], vercel: [], netlify: [], terraform: [], ansible: [],
  nginx: [], linux: [], ubuntu: [], archlinux: ['arch'], git: [], github: [], githubactions: ['actions'], gitlab: [], grafana: [],
  prometheus: [], jest: [], vitest: [], eslint: [], prettier: [], npm: [], pnpm: [], yarn: [], postman: [], figma: [], neovim: ['nvim'],
  vim: [], jetbrains: [], notion: [], raspberrypi: ['raspberry'], arduino: [], unity: [], godotengine: ['godot'], blender: []
};

const out = {};
const aliases = {};
const missing = [];
for (const [slug, extra] of Object.entries(WANTED)) {
  const key = 'si' + slug[0].toUpperCase() + slug.slice(1);
  const icon = si[key];
  if (!icon) {
    missing.push(slug);
    continue;
  }
  if (icon.path.length > MAX_PATH) {
    missing.push(`${slug} (too large)`);
    continue;
  }
  out[slug] = { t: icon.title, h: icon.hex, p: icon.path };
  for (const a of extra) aliases[a] = slug;
}

const body = `// Generated by scripts/gen-tech-icons.mjs from simple-icons (CC0 1.0). Do not edit by hand.
// ${Object.keys(out).length} icons. Brand names and logos are trademarks of their respective owners.

export interface TechIcon {
  /** Display title */
  t: string;
  /** Brand colour, hex without # */
  h: string;
  /** SVG path in a 24x24 box */
  p: string;
}

export const TECH_ICONS: Record<string, TechIcon> = ${JSON.stringify(out)};

/** Common spellings -> slug. */
export const TECH_ALIASES: Record<string, string> = ${JSON.stringify(aliases)};
`;
writeFileSync(new URL('../src/svg/tech-icons.ts', import.meta.url), body);
console.log(`wrote ${Object.keys(out).length} icons (${(body.length / 1024).toFixed(0)} KB); skipped: ${missing.join(', ') || 'none'}`);
